"""Render every generated document from its registry (`make docs`).

Two kinds of output:
- whole files, such as docs/planted-items.md from platform/planted/registry.yaml;
- marked blocks inside hand-written files, between `<!-- generated:<block> -->` and
  `<!-- /generated:<block> -->`, such as the demo table and the demo runbook in each section's
  demo/README.md; in a shell script the markers are `# generated:<block>` and
  `# /generated:<block>` lines, such as the demo list in each section's demo/run.sh.

Edit the registry or the template in templates/, never the generated text.
`--check` writes nothing and exits 1 when any output is out of date (CI and the release gate).

Both modes also check every walkthrough excerpt: under a heading `### <path>, lines a-b`, the code
block's first line is the comment `# <path> (lines a-b)` and the rest is exactly lines a to b of
that file today, so an excerpt can never drift from the code it explains.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from datapilot.contracts import registries
from datapilot.contracts.registries import PlantedKind
from datapilot.names import SECTIONS, SECTIONS_BY_SLUG
from datapilot.settings import REPO

TEMPLATES = Path(__file__).resolve().parent / "templates"
ENV = Environment(
    loader=FileSystemLoader(TEMPLATES),
    undefined=StrictUndefined,
    keep_trailing_newline=True,
    trim_blocks=True,
    lstrip_blocks=True,
)
GENERATED_NOTE = "Generated by `make docs` from {source}. Edit that file, not this page."
# Registry text quoted on a page keeps the registry's words. Where a word means a business day
# ("yesterday's KPIs" for the digest), not the day the page was written, the line carries the prose
# lint's allow marker (docs/STYLE.md, rule 15); rewording the registry removes the marker.
_DATED = re.compile(r"\b(?:tonight|tomorrow|yesterday|last night)\b", re.I)
LINT_ALLOW = " <!-- lint-prose: allow -->"


def quoted(text: str) -> str:
    return text + LINT_ALLOW if _DATED.search(text) else text


ENV.filters["quoted"] = quoted


@dataclass(frozen=True)
class Output:
    path: Path
    render: Callable[[str], str]  # current text -> new text


def _whole(template: str, **context: object) -> Callable[[str], str]:
    return lambda _current: ENV.get_template(template).render(**context)


_LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s")


def _gaps(body: str) -> tuple[str, str]:
    """The line breaks around a Markdown block's body: a heading or a list next to a marker gets a
    blank line between them, as Markdown wants (the Markdown lint, .pymarkdown.yaml)."""
    lines = body.split("\n")
    first, last = lines[0], lines[-1]
    before = "\n\n" if first.startswith("#") or _LIST_ITEM.match(first) else "\n"
    after = "\n\n" if last.startswith("#") or _LIST_ITEM.match(last) else "\n"
    return before, after


def _block(
    name: str, template: str, *, shell: bool = False, **context: object
) -> Callable[[str], str]:
    if shell:
        begin, end = f"# generated:{name}", f"# /generated:{name}"
    else:
        begin, end = f"<!-- generated:{name} -->", f"<!-- /generated:{name} -->"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)

    def render(current: str) -> str:
        if begin not in current:
            raise SystemExit(f"x missing marker {begin}")
        body = ENV.get_template(template).render(**context).strip("\n")
        before, after = ("\n", "\n") if shell else _gaps(body)
        return pattern.sub(lambda _m: f"{begin}{before}{body}{after}{end}", current, count=1)

    return render


def _all(*renders: Callable[[str], str]) -> Callable[[str], str]:
    """Several blocks in one file, applied in order."""

    def render(current: str) -> str:
        for one in renders:
            current = one(current)
        return current

    return render


def outputs() -> list[Output]:
    demo_registry = registries.demos()
    planted_registry = registries.planted()
    kinds = [
        (PlantedKind.CODE_BUG, "Code bugs"),
        (PlantedKind.HARNESS_WEAKNESS, "Harness weaknesses"),
        (PlantedKind.DATA_CONDITION, "Data conditions"),
        (PlantedKind.DEMO_AID, "Demo aids"),
    ]
    out = [
        Output(
            REPO / "docs" / "planted-items.md",
            _whole(
                "planted-items.md.j2",
                groups=[
                    (title, [i for i in planted_registry.items if i.kind is k])
                    for k, title in kinds
                ],
                demos={d.id: d for d in demo_registry.demos},
                sections=SECTIONS_BY_SLUG,
                note=GENERATED_NOTE.format(source="`platform/planted/registry.yaml`"),
            ),
        )
    ]
    planted_by_id = {i.id: i for i in planted_registry.items}
    # What each section's run.sh passes PLANTED=1 to, when the script runs with PLANTED=1: the
    # demos with a planted code bug, the only ones make demo takes it for.
    planted_demos = {
        d.id
        for d in demo_registry.demos
        if any(
            p in planted_by_id and planted_by_id[p].kind is PlantedKind.CODE_BUG for p in d.planted
        )
    }
    for section in SECTIONS:
        demos = demo_registry.for_section(section.slug)
        context = {
            "demos": demos,
            "section": section,
            "planted": planted_by_id,
            "planted_demos": planted_demos,
        }
        out.append(
            Output(
                REPO / section.folder / "demo" / "README.md",
                _all(
                    _block("demo-table", "demo-table.md.j2", **context),
                    _block("demo-runbook", "demo-runbook.md.j2", **context),
                ),
            )
        )
        out.append(
            Output(
                REPO / section.folder / "demo" / "run.sh",
                _block("demo-list", "demo-list.sh.j2", shell=True, **context),
            )
        )
    return out


# --- Walkthrough excerpts -------------------------------------------------------------------------
EXCERPT_PAGES = ("section-*/demo/walkthrough.md", "final-project/walkthrough.md")
CODE_SECTION = "The code, explained"
_HEADING = re.compile(r"^### `?(?P<path>[^`,\s]+)`?, lines (?P<a>\d+)-(?P<b>\d+)\s*$")
_COMMENT = re.compile(r"^(?:#|--|//)\s*(?P<path>\S+) \(lines (?P<a>\d+)-(?P<b>\d+)\)\s*$")
_FENCE = re.compile(r"^(```+|~~~+)\s*(?P<lang>[\w-]*)")
_NOT_CODE = {"mermaid", "text"}


@dataclass(frozen=True)
class Excerpt:
    line: int  # the heading's line number on the page
    path: str
    first: int
    last: int
    fence_line: int | None  # the code block's opening line, None when there is none
    code: tuple[str, ...]  # the block's lines, the comment line included


@dataclass(frozen=True)
class _Block:
    line: int
    lang: str
    code: tuple[str, ...]


def _blocks(lines: list[str]) -> list[tuple[int, str, _Block | None]]:
    """Each heading and code block in order: (line number, heading text or '', block or None)."""
    out: list[tuple[int, str, _Block | None]] = []
    index = 0
    while index < len(lines):
        text = lines[index]
        opening = _FENCE.match(text)
        if opening:
            marker, start, body = opening.group(1), index + 1, []
            index += 1
            while index < len(lines) and not lines[index].startswith(marker):
                body.append(lines[index])
                index += 1
            out.append((start, "", _Block(start, opening.group("lang"), tuple(body))))
        elif text.startswith("#"):
            out.append((index + 1, text, None))
        index += 1
    return out


def _is_section(heading: str) -> bool:
    """An H1 or H2: it ends the current excerpt and, maybe, the code section."""
    return heading.startswith(("# ", "## "))


def _is_code_section(heading: str) -> bool:
    return heading.rstrip() == f"## {CODE_SECTION}"


def excerpts_in(text: str) -> list[Excerpt]:
    """The excerpts under the page's code section, each with the first code block after it."""
    found: list[Excerpt] = []
    in_code_section = False
    current: dict[str, object] | None = None

    def close() -> None:
        if current is not None:
            found.append(Excerpt(**current))  # type: ignore[arg-type]

    for line, heading, block in _blocks(text.splitlines()):
        if block is None:
            if _is_section(heading):
                close()
                current = None
                in_code_section = _is_code_section(heading)
                continue
            if heading.startswith("### ") and in_code_section:
                close()
                match = _HEADING.match(heading)
                current = None
                if match:
                    current = {
                        "line": line,
                        "path": match["path"],
                        "first": int(match["a"]),
                        "last": int(match["b"]),
                        "fence_line": None,
                        "code": (),
                    }
            continue
        if current is not None and current["fence_line"] is None:
            current["fence_line"], current["code"] = block.line, block.code
    close()
    return found


def _stray_blocks(text: str) -> list[int]:
    """Code blocks in the code section that sit under no excerpt heading."""
    stray, in_code_section, owner, taken = [], False, False, False
    for line, heading, block in _blocks(text.splitlines()):
        if block is None:
            if _is_section(heading):
                in_code_section, owner = _is_code_section(heading), False
            elif heading.startswith("### "):
                owner, taken = bool(_HEADING.match(heading)), False
            continue
        if not in_code_section or block.lang in _NOT_CODE:
            continue
        if owner and not taken:
            taken = True
            continue
        stray.append(line)
    return stray


def _excerpt_problems(page: str, excerpt: Excerpt, root: Path) -> list[str]:
    where = f"x {page}:{excerpt.line}: {excerpt.path}, lines {excerpt.first}-{excerpt.last}"
    if excerpt.fence_line is None:
        return [f"{where}: no code block under the heading"]
    if excerpt.path.startswith("/") or ".." in Path(excerpt.path).parts:
        return [f"{where}: the path must be relative to the repository root"]
    if excerpt.first < 1 or excerpt.first > excerpt.last:
        return [f"{where}: the range {excerpt.first}-{excerpt.last} is backwards or empty"]
    comment = _COMMENT.match(excerpt.code[0]) if excerpt.code else None
    expected = f"# {excerpt.path} (lines {excerpt.first}-{excerpt.last})"
    if comment is None or (comment["path"], int(comment["a"]), int(comment["b"])) != (
        excerpt.path,
        excerpt.first,
        excerpt.last,
    ):
        return [f"{where}: the block's first line must be the comment '{expected}'"]
    source = root / excerpt.path
    if not source.is_file():
        return [f"{where}: no file {excerpt.path}"]
    file_lines = source.read_text(encoding="utf-8").splitlines()
    if excerpt.last > len(file_lines):
        return [f"{where}: {excerpt.path} has {len(file_lines)} lines"]
    want = file_lines[excerpt.first - 1 : excerpt.last]
    have = list(excerpt.code[1:])
    for offset, (wanted, shown) in enumerate(zip(want, have, strict=False)):
        if wanted != shown:
            return [
                f"{where}: differs from {excerpt.path} at line {excerpt.first + offset}: "
                f"the file has {wanted.strip()!r}, the page shows {shown.strip()!r}"
            ]
    if len(have) != len(want):
        return [f"{where}: the block holds {len(have)} lines, the range has {len(want)}"]
    return []


def excerpt_problems_in(page: str, text: str, root: Path) -> list[str]:
    problems: list[str] = []
    for excerpt in excerpts_in(text):
        problems += _excerpt_problems(page, excerpt, root)
    for line in _stray_blocks(text):
        problems.append(
            f"x {page}:{line}: a code block in '{CODE_SECTION}' has no '<path>, lines a-b' heading"
        )
    return problems


def excerpt_pages(root: Path) -> list[Path]:
    return sorted(path for pattern in EXCERPT_PAGES for path in root.glob(pattern))


def excerpt_problems(root: Path) -> list[str]:
    problems: list[str] = []
    for path in excerpt_pages(root):
        page = path.relative_to(root).as_posix()
        problems += excerpt_problems_in(page, path.read_text(encoding="utf-8"), root)
    return problems


def run(check: bool) -> int:
    stale = []
    for output in outputs():
        current = output.path.read_text(encoding="utf-8") if output.path.exists() else ""
        new = output.render(current)
        if new != current:
            stale.append(output.path.relative_to(REPO).as_posix())
            if not check:
                output.path.write_text(new, encoding="utf-8", newline="\n")
    verb = "out of date" if check else "written"
    for path in stale:
        print(f"{'x' if check else '+'} {path} {verb}")
    print(f"docs: {len(stale)} {verb}")
    return 1 if check and stale else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if stale")
    args = parser.parse_args(argv)
    problems = registries.cross_check(registries.demos(), registries.planted())
    if problems:
        print("\n".join(f"x {p}" for p in problems))
        return 1
    status = run(args.check)
    drifted = excerpt_problems(REPO)
    for problem in drifted:
        print(problem)
    print(f"walkthrough excerpts: {len(drifted)} out of step with the code")
    return 1 if drifted else status


if __name__ == "__main__":
    sys.exit(main())
