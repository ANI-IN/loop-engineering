"""The only path the agent's SQL takes to the database.

Each query runs as the read-only agent role, in a transaction marked READ ONLY, with a local
statement timeout and search path, and is always rolled back. The original text is executed, never
SQL regenerated by a parser. Database errors become short feedback the agent can act on, with
every quoted part of the message redacted: PostgreSQL quotes the value it could not use, and that
value can be personal data no person approved.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any

import psycopg

from datapilot.contracts import QueryResult
from datapilot.planted import planted

READ_ONLY_SQLSTATE = "25006"
# A write the database refused: the read-only transaction (25006) or the role's grants (42501).
# The verification loop ends such a run escalated at once and never feeds it back as a retry.
REFUSED_WRITE_SQLSTATES = frozenset({READ_ONLY_SQLSTATE, "42501"})
_FEEDBACK = {
    "25006": "Write blocked: the connection is read-only. Only SELECT queries can run.",
    "42501": "Permission denied: the agent role can only read the allowed schema.",
    "57014": "The query hit the statement timeout. Add filters or aggregate before returning.",
    "42P01": "Unknown table. Use list_tables to see the tables that exist.",
    "42703": "Unknown column. Use describe_table to see the real column names.",
    "42601": "Syntax error. Send one valid SELECT statement.",
    "42883": "Unknown function or wrong argument types. Cast the arguments or use another one.",
    "22012": "Division by zero. Guard the divisor with NULLIF(..., 0).",
}
REDACTED = '"<redacted>"'
DATA_EXCEPTION_CLASS = "22"  # a value could not be converted, or is out of range


def redact(message: str) -> str:
    """The message with its quoted part replaced, from the first double quote to the last, so a
    value holding a quote of its own cannot leave a piece behind; with one quote, everything after
    it. PostgreSQL quotes the value an error is about ('invalid input syntax for type integer:
    "a value"'), and an identifier it could not find, which a cast such as ::regclass takes from the
    data; the text outside the quotes keeps the kind of error."""
    first, last = message.find('"'), message.rfind('"')
    if first < 0:
        return message
    if first == last:
        return message[:first] + REDACTED
    return message[:first] + REDACTED + message[last + 1 :]


class ExecutionError(RuntimeError):
    """A database error with its SQLSTATE and its message, redacted (redact): the message reaches
    the agent, the graders' reasons, the run's events, and its trace."""

    def __init__(self, sqlstate: str | None, message: str) -> None:
        message = redact(message)
        super().__init__(message)
        self.sqlstate = sqlstate or ""
        self.message = message

    @property
    def refused_write(self) -> bool:
        return self.sqlstate in REFUSED_WRITE_SQLSTATES

    @property
    def feedback(self) -> str:
        if self.sqlstate in _FEEDBACK:
            return _FEEDBACK[self.sqlstate]
        if self.sqlstate.startswith(DATA_EXCEPTION_CLASS):
            return (
                f"A value did not fit ({self.message}). Cast or compare only columns whose "
                "values fit the type."
            )
        return f"The database refused the query: {self.message}"


class ReadOnlyProbeFailed(RuntimeError):
    """The agent connection's role can write, or the probe could not reach it: refuse to start."""


# The startup probe, on a plain connection (no SET TRANSACTION): what the role itself may do.
_ROLE_PROBE_SQL = """
SELECT (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) AS superuser,
       (SELECT string_agg(c.relname, ', ' ORDER BY c.relname)
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = %(schema)s AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
          AND (has_table_privilege(c.oid, 'INSERT') OR has_table_privilege(c.oid, 'UPDATE')
               OR has_table_privilege(c.oid, 'DELETE') OR has_table_privilege(c.oid, 'TRUNCATE'))
       ) AS writable,
       (SELECT string_agg(nspname, ', ' ORDER BY nspname) FROM pg_namespace
        WHERE has_schema_privilege(oid, 'CREATE')) AS creatable,
       has_database_privilege(current_database(), 'TEMP') AS temp
"""


@dataclass(frozen=True)
class Executor:
    url: str
    schema: str
    statement_timeout_ms: int

    def _begin(self, conn: psycopg.Connection[Any]) -> None:
        conn.execute("SET TRANSACTION READ ONLY")
        conn.execute(
            "SELECT set_config('statement_timeout', %s, true), set_config('search_path', %s, true)",
            (f"{self.statement_timeout_ms}ms", self.schema),
        )

    def run(self, sql: str) -> QueryResult:
        """Every row of the result; the caller applies the row cap."""
        try:
            with psycopg.connect(self.url) as conn:
                self._begin(conn)
                try:
                    cursor = _execute_one(conn, sql)  # the original text
                    columns = [d.name for d in cursor.description or []]
                    rows = cursor.fetchall() if cursor.description else []
                finally:
                    conn.rollback()
        except psycopg.Error as error:
            # from None: a chained database error would carry its raw message, value and all, into
            # any traceback a log or a trace records
            raise ExecutionError(error.sqlstate, _first_line(error)) from None
        return QueryResult(columns=columns, rows=rows, total_row_count=len(rows), truncated=False)

    def explain(self, sql: str) -> dict[str, Any]:
        """The top plan node of EXPLAIN (FORMAT JSON), without running the query."""
        try:
            with psycopg.connect(self.url) as conn:
                self._begin(conn)
                try:
                    # Only a read-only SELECT is ever explained (the cost grader), so this one
                    # always goes as one prepared statement (see _prepared).
                    text, params = _prepared("EXPLAIN (FORMAT JSON) " + sql)
                    row = conn.execute(text, params, prepare=True).fetchone()
                finally:
                    conn.rollback()
        except psycopg.Error as error:
            raise ExecutionError(error.sqlstate, _first_line(error)) from None
        plan = row[0] if row else []
        if isinstance(plan, str):
            plan = json.loads(plan)
        return plan[0]["Plan"]

    def probe_read_only(self) -> None:
        """The role behind the connection must be unable to write, whatever the transaction: not
        a superuser, no INSERT, UPDATE, DELETE, or TRUNCATE on a table of the schema, no CREATE on
        any schema, no temporary tables. A write inside a read-only transaction fails for any
        role, so trying one proves nothing about the role (review round 1)."""
        try:
            with psycopg.connect(self.url) as conn:
                try:
                    row = conn.execute(_ROLE_PROBE_SQL, {"schema": self.schema}).fetchone()
                finally:
                    conn.rollback()
        except psycopg.OperationalError as error:
            raise ReadOnlyProbeFailed(
                f"read-only probe could not connect to the agent database: {_first_line(error)}"
            ) from error
        superuser, writable, creatable, temp = row or (True, None, None, True)
        problems = [
            *(["the role is a superuser"] if superuser else []),
            *([f"it can write {writable}"] if writable else []),
            *([f"it can create objects in schema {creatable}"] if creatable else []),
            *(["it can create temporary tables"] if temp else []),
        ]
        if problems:
            raise ReadOnlyProbeFailed(
                "the agent connection is not read-only: " + "; ".join(problems)
            )


def _prepared(sql: str) -> tuple[str, tuple[()]]:
    """The text as one prepared statement: %% keeps every % literal under the empty parameter
    list. psycopg sends a query with no parameters by the simple protocol, which runs every
    statement in the text; a prepared statement holds exactly one, and PostgreSQL refuses a second
    (42601) before anything runs, even if a parser and PostgreSQL disagreed on where one ends."""
    return sql.replace("%", "%%"), ()


def _execute_one(conn: psycopg.Connection[Any], sql: str) -> psycopg.Cursor[Any]:
    """Run the agent's text as one statement only (_prepared). The naive guard's demo needs its
    stacked statement to reach the read-only transaction, so with that planted item on the text
    goes by the simple protocol, as it is."""
    if planted("BUG_NAIVE_GUARD"):
        return conn.execute(sql)  # planted: "SELECT 1; DELETE FROM orders" reaches the database
    text, params = _prepared(sql)
    return conn.execute(text, params, prepare=True)


def _first_line(error: psycopg.Error) -> str:
    return (str(error).strip().splitlines() or [type(error).__name__])[0]


@dataclass(frozen=True)
class WarehouseRunner:
    """The executor behind the evaluator's one-method SqlRunner interface
    (run(sql, warehouse, *, max_rows)): one executor per warehouse database."""

    executors: dict[str, Executor]

    def run(self, sql: str, warehouse: str, *, max_rows: int) -> QueryResult:
        result = self.executors[warehouse].run(sql)
        return QueryResult(
            columns=result.columns,
            rows=result.rows[:max_rows],
            total_row_count=result.total_row_count,
            truncated=result.total_row_count > max_rows,
        )
